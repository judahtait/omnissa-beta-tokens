import Foundation
import Testing
@testable import BetaTokensCore

// Fabricated credentials only - never real Apple data.
// Uses Swift Testing (ships with the Xcode command line tools; XCTest needs full Xcode).

private let fake = Credentials(consumerKey: "CK_FAKE", consumerSecret: "CS_FAKE",
                               accessToken: "AT_FAKE", accessSecret: "AS_FAKE")

private func tempDir() -> URL {
    let base = ProcessInfo.processInfo.environment["OBT_TMP"] ?? NSTemporaryDirectory()
    return URL(fileURLWithPath: base).appendingPathComponent("obt-\(UUID().uuidString)")
}

private func makeP7M(dir: URL, payload: String) throws -> URL {
    let out = dir.appendingPathComponent("fake.p7m")
    let r = try ServerToken.runOpenSSL(
        ["smime", "-encrypt", "-aes256", "-out", out.path, dir.appendingPathComponent(ServerToken.certName).path],
        input: Data(payload.utf8))
    #expect(r.status == 0, "\(String(decoding: r.err, as: UTF8.self))")
    return out
}

@Suite struct OAuthTests {
    // Expected header generated by the Python implementation (src/omnissa_beta_tokens/oauth.py)
    // with identical inputs, so this proves the Swift port signs identically.
    @Test func matchesPythonReference() {
        let h = OAuth1.header(method: "GET", url: ABMClient.sessionURL, credentials: fake,
                              timestamp: 1_700_000_000, nonce: "abcd1234abcd1234")
        let expected = "OAuth realm=\"ADM\",oauth_consumer_key=\"CK_FAKE\",oauth_nonce=\"abcd1234abcd1234\"," +
            "oauth_signature_method=\"HMAC-SHA1\",oauth_timestamp=\"1700000000\",oauth_token=\"AT_FAKE\"," +
            "oauth_version=\"1.0\",oauth_signature=\"RtK5Tl8tInvxynxWC5uWpDJzDj8%3D\""
        #expect(h == expected)
    }

    @Test func urlEncode() { #expect(OAuth1.urlEncode("a b/c~") == "a%20b%2Fc~") }

    @Test func secretsNeverInDescription() {
        #expect(!"\(fake)".contains("CS_FAKE"))
        #expect(!"\(fake)".contains("AS_FAKE"))
        #expect(!"\(BetaToken(title: "t", os: "iOS", token: String(repeating: "T", count: 40)))".contains("TTTT"))
    }
}

@Suite struct ServerTokenTests {
    @Test func keypairPermissionsAndNoOverwrite() throws {
        let dir = tempDir()
        let (key, _) = try ServerToken.generateKeypair(in: dir)
        let mode = try FileManager.default.attributesOfItem(atPath: key.path)[.posixPermissions] as? Int
        #expect(mode == 0o600)
        #expect(throws: (any Error).self) { try ServerToken.generateKeypair(in: dir) }
    }

    @Test func decryptRoundTrip() throws {
        let dir = tempDir()
        try ServerToken.generateKeypair(in: dir)
        let json = #"{"consumer_key":"CK_FAKE","consumer_secret":"CS_FAKE","access_token":"AT_FAKE","access_secret":"AS_FAKE","access_token_expiry":"2099-01-01T00:00:00Z"}"#
        let p7m = try makeP7M(dir: dir, payload: "-----BEGIN MESSAGE-----\n\(json)\n-----END MESSAGE-----\n")
        let creds = try ServerToken.decrypt(p7m: p7m, workdir: dir)
        #expect(creds.consumerKey == "CK_FAKE")
        #expect(creds.accessTokenExpiry == "2099-01-01T00:00:00Z")
    }

    @Test func wrongCertFails() throws {
        let a = tempDir(), b = tempDir()
        try ServerToken.generateKeypair(in: a)
        try ServerToken.generateKeypair(in: b)
        let p7m = try makeP7M(dir: a, payload: "{}")
        #expect(throws: (any Error).self) { try ServerToken.decrypt(p7m: p7m, workdir: b) }
    }
}

@Suite struct ABMClientTests {
    @Test func fetchWithFakeTransport() async throws {
        let tokensBody = #"{"betaEnrollmentTokens":[{"title":"macOS Test Beta","os":"OSX","token":"TTTTTTTTTTTTTTTTTTTT"},{"title":"iOS Test Beta","os":"iOS","token":"UUUUUUUUUUUUUUUUUUUU"}]}"#
        let client = ABMClient { req in
            let url = req.url!.absoluteString
            if url == ABMClient.sessionURL {
                #expect(req.value(forHTTPHeaderField: "Authorization")!.hasPrefix("OAuth realm=\"ADM\""))
                return (Data(#"{"auth_session_token":"S"}"#.utf8), 200)
            }
            #expect(req.value(forHTTPHeaderField: "X-ADM-Auth-Session") == "S")
            #expect(req.value(forHTTPHeaderField: "X-Server-Protocol-Version") == "1")
            return (Data(tokensBody.utf8), 200)
        }
        let tokens = try await client.fetchBetaTokens(fake)
        #expect(Set(tokens.map(\.osDisplay)) == ["macOS", "iOS"])
    }

    @Test func seedTurnedOffMessage() async {
        let client = ABMClient { _ in (Data(#"{"reason":"APPLE_SEED_FOR_IT_TURNED_OFF"}"#.utf8), 403) }
        do {
            _ = try await client.betaTokens(session: "S")
            Issue.record("expected an error")
        } catch {
            #expect(error.localizedDescription.contains("beta.apple.com/for-it"))
        }
    }

    @Test func sessionFailure() async {
        let client = ABMClient { _ in (Data(), 401) }
        do {
            _ = try await client.sessionToken(fake)
            Issue.record("expected an error")
        } catch {
            #expect(error.localizedDescription.contains("401"))
        }
    }
}

@Suite struct RenderTests {
    let toks = [BetaToken(title: "macOS Test Beta", os: "OSX", token: String(repeating: "M", count: 40)),
                BetaToken(title: "iOS Test Beta", os: "iOS", token: String(repeating: "I", count: 40))]

    @Test func filterByOSAndText() {
        #expect(Render.filter(toks, os: "macOS").count == 1)
        #expect(Render.filter(toks, text: "ios").count == 1)
    }

    @Test func enrollmentModesMatchUemGuidance() {
        #expect(EnrollmentMode.automatic.programEnrollment == .alwaysOn)
        #expect(EnrollmentMode.automatic.usesRequireProgram)
        #expect(!EnrollmentMode.automatic.usesOfferPrograms)

        #expect(EnrollmentMode.offer.programEnrollment == .allowed)
        #expect(EnrollmentMode.offer.usesOfferPrograms)
        #expect(!EnrollmentMode.offer.usesRequireProgram)

        #expect(EnrollmentMode.offerAlwaysOn.programEnrollment == .alwaysOn)
        #expect(EnrollmentMode.offerAlwaysOn.usesOfferPrograms)

        #expect(EnrollmentMode.off.programEnrollment == .alwaysOff)
        #expect(!EnrollmentMode.off.usesRequireProgram)
        #expect(!EnrollmentMode.off.usesOfferPrograms)

        for mode in EnrollmentMode.allCases where mode.usesRequireProgram {
            #expect(mode.programEnrollment == .alwaysOn)
            #expect(!mode.usesOfferPrograms)
        }
    }
}
