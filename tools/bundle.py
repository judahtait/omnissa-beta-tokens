#!/usr/bin/env python3
"""Bundle the package into one readable, dependency-free script.

Usage: python3 tools/bundle.py [out_path]   (default: dist/omnissa-beta-tokens.py)

Flattens oauth, servertoken, abm, render and cli into a single file so it can
be downloaded from the guide and audited by customers.
"""

from __future__ import annotations

import re
import stat
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PKG = ROOT / "src" / "omnissa_beta_tokens"
ORDER = ["oauth", "servertoken", "abm", "render", "cli"]

REL_IMPORT = re.compile(r"^from \.[\w.]* import (?:\([^)]*\)|[^\n]*)\n", re.M)
STD_IMPORT = re.compile(r"^(?:import [\w.]+|from [\w.]+ import [^(\n]+)$", re.M)
DOCSTRING = re.compile(r'\A"""(.*?)"""\n', re.S)


def version() -> str:
    m = re.search(r'__version__ = "([^"]+)"', (PKG / "__init__.py").read_text())
    return m.group(1)


def main() -> int:
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "dist" / "omnissa-beta-tokens.py"
    imports: set[str] = set()
    bodies: list[str] = []
    for name in ORDER:
        text = (PKG / f"{name}.py").read_text(encoding="utf-8")
        text = DOCSTRING.sub("", text, count=1)
        text = REL_IMPORT.sub("", text)
        if name == "cli":
            text = re.sub(r"\brender\.", "", text)  # render module is now flat
        for m in STD_IMPORT.finditer(text):
            line = m.group(0)
            if line != "from __future__ import annotations":
                imports.add(line)
        text = STD_IMPORT.sub("", text)
        text = text.replace("from __future__ import annotations\n", "")
        bodies.append(f"# ---- {name} " + "-" * (60 - len(name)) + "\n" + text.strip() + "\n")

    header = (
        '#!/usr/bin/env python3\n'
        '"""Omnissa Beta Token Utility (single-file build).\n\n'
        'Get Apple beta enrollment tokens (AppleSeed for IT) for a Workspace ONE UEM\n'
        'declarative Software Update Settings profile. Python 3.9+, standard library\n'
        'plus the system openssl. Generated by tools/bundle.py - do not edit.\n\n'
        'Copyright (c) 2026 Omnissa, LLC. MIT License. Includes logic adapted from the\n'
        'MIT-licensed microsoft/shell-intune-samples betaTokens.sh (see NOTICE).\n'
        '"""\n\n'
        "from __future__ import annotations\n\n"
        + "\n".join(sorted(imports))
        + f'\n\n__version__ = "{version()}"\n\n\n'
    )
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(header + "\n\n".join(bodies), encoding="utf-8")
    out.chmod(out.stat().st_mode | stat.S_IXUSR)
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
